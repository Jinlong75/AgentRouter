import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

const types = ['code', 'fix', 'test', 'refactor'];
const specRequired = { sections: ['受影响的已有测试'], types };
const reportRequired = { sections: ['推断清单', 'TODO(lead)', '已知问题'], types };

test('初始化默认启用必填检查，旧项目可选择补入', t => {
  const dir = mkdtempSync(join(tmpdir(), 'ar-init-required-'));
  t.after(() => rmSync(dir, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 }));
  const root = join(dir, 'repo'), home = join(dir, 'home');
  mkdirSync(root); mkdirSync(home);
  const git = (...args) => execFileSync('git', args, { cwd: root });
  git('init', '-q', '-b', 'main'); git('config', 'user.name', 'Test'); git('config', 'user.email', 'test@example.invalid');
  const env = { ...process.env, AGENT_ROUTER_HOME: home, AR_WORKTREE_ROOT: join(dir, 'worktrees'), AR_NO_WATCH: '1', AR_TEST_AGENT: '1' };
  const ar = (...args) => spawnSync(process.execPath, [resolve('core/ar.mjs'), ...args, '--json'], { cwd: root, env, encoding: 'utf8', timeout: 60000 });
  const fake = report => writeFileSync(join(home, 'config.json'), JSON.stringify({ v: 2, managed: false, watchWindow: 'never', defaultProfile: 'fake', profiles: { fake: { adapter: 'fake', enabled: true, events: [], report, exit: 0 } } }));
  fake('OK\n');
  const init = ar('init'); assert.equal(init.status, 0, init.stderr + init.stdout);
  const configPath = join(root, '.agent-router', 'project.json');
  const config = JSON.parse(readFileSync(configPath, 'utf8'));
  assert.deepEqual(config.specRequired, specRequired); assert.deepEqual(config.reportRequired, reportRequired);
  t.diagnostic(`初始化配置：\n${readFileSync(configPath, 'utf8')}`);
  git('add', '--', '.agent-router/project.json', '.gitignore', 'AGENTS.md', 'CLAUDE.md', 'docs', 'handoff.md');
  git('commit', '-qm', 'init');
  const task = (type, section = '') => `---\ntype: ${type}\nallowed_paths:\n  - task.md\nexpect_commit: false\nmax_retries: 0\n---\n任务\n${section}`;
  const spec = join(root, 'task.md');
  writeFileSync(spec, task('code'));
  git('add', '--', 'task.md'); git('commit', '-qm', 'missing section');
  const rejected = ar('dispatch', 'task.md', '--profile', 'fake');
  assert.equal(rejected.status, 2); assert.match(rejected.stdout + rejected.stderr, /任务说明缺少必填项.*受影响的已有测试/);
  writeFileSync(spec, task('code', '## 受影响的已有测试\n无\n'));
  git('add', '--', 'task.md'); git('commit', '-qm', 'fixtures');
  const failed = ar('dispatch', 'task.md', '--name', 'missing-report', '--profile', 'fake');
  assert.equal(failed.status, 3, failed.stderr + failed.stdout);
  const gate = name => JSON.parse(readFileSync(join(root, '.agent-runs', name, 'attempts', '1', 'gate.json'), 'utf8'));
  assert.equal(gate('missing-report').summary, '汇报缺少必需的小节：推断清单、TODO(lead)、已知问题（项目配置 reportRequired）');
  fake(['完成了什么', '改动了哪些文件', 'TODO(lead) 清单', '推断清单', '偏离说明', '已知问题'].map(h => `## ${h}\n无\n`).join('\n'));
  const passed = ar('dispatch', 'task.md', '--name', 'complete-report', '--profile', 'fake');
  assert.equal(passed.status, 0, passed.stderr + passed.stdout); assert.equal(gate('complete-report').ok, true);
  fake('OK\n'); writeFileSync(spec, task('docs'));
  git('add', '--', 'task.md'); git('commit', '-qm', 'docs');
  const docs = ar('dispatch', 'task.md', '--name', 'docs', '--profile', 'fake');
  assert.equal(docs.status, 0, docs.stderr + docs.stdout); assert.equal(gate('docs').ok, true);
  const { specRequired: ignoredSpec, reportRequired: ignoredReport, ...old } = config;
  writeFileSync(configPath, JSON.stringify(old, null, 2) + '\n');
  const before = readFileSync(configPath, 'utf8');
  const plan = ar('init', '--upgrade', '--dry-run'); assert.equal(plan.status, 0, plan.stderr + plan.stdout);
  const fields = JSON.parse(plan.stdout).changes.filter(c => c.action === 'configField');
  assert.deepEqual(fields.map(c => c.key), ['specRequired', 'reportRequired']);
  assert.equal(readFileSync(configPath, 'utf8'), before);
  const upgrade = ar('init', '--upgrade', '--add-field', 'specRequired,reportRequired'); assert.equal(upgrade.status, 0, upgrade.stderr + upgrade.stdout);
  const after = readFileSync(configPath, 'utf8');
  assert.deepEqual(JSON.parse(after), config);
  assert.ok(after.startsWith(before.slice(0, before.lastIndexOf('\n}'))));
});
