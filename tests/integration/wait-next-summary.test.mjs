test('wait 摘要包含本任务结束采样触发的调整', async t => {
  const base = mkdtempSync(join(tmpdir(), 'ar-summary-adjust-')), root = join(base, 'repo'), home = join(base, 'home');
  t.after(() => rmSync(base, { recursive: true, force: true }));
  mkdirSync(root); mkdirSync(home);
  const git = (...args) => { const r = spawnSync('git', args, { cwd: root, encoding: 'utf8', shell: false }); assert.equal(r.status, 0, r.stderr); };
  git('init', '-q'); git('config', 'user.name', 'Test'); git('config', 'user.email', 'test@example.invalid');
  writeFileSync(join(root, 'fixture.txt'), 'fixture'); git('add', 'fixture.txt'); git('commit', '-qm', 'fixture');
  writeFileSync(join(home, 'config.json'), JSON.stringify({ v: 2, managed: false, watchWindow: 'never', concurrency: 'auto', concurrencyMax: 4, defaultProfile: 'fake', profiles: { fake: { adapter: 'fake', label: 'fake', enabled: true, events: [], report: 'ok', exit: 0 } } }));
  writeFileSync(join(home, 'concurrency-state.json'), JSON.stringify({ limit: 2, consumed: [], window: [], event: null }));
  const load = join(base, 'load.json'); writeFileSync(load, JSON.stringify({ cpu: 10, freeGb: 1.46 }));
  const env = { ...process.env, AGENT_ROUTER_HOME: home, AR_NO_WATCH: '1', AR_WORKTREE_ROOT: join(base, 'worktrees'), AR_TEST_LOAD_FILE: load };
  const entry = fileURLToPath(new URL('../../core/ar.mjs', import.meta.url));
  const child = spawn(process.execPath, [entry, '示例任务', '--name', 'sample', '--profile', 'fake'], { cwd: root, env, stdio: 'ignore', shell: false });
  const exit = new Promise((resolve, reject) => { child.on('error', reject); child.on('exit', resolve); });
  const runs = join(home, 'runs.jsonl');
  for (let i = 0; i < 200 && (!existsSync(runs) || !readFileSync(runs, 'utf8').includes('"event":"start"')); i++) await new Promise(resolve => setTimeout(resolve, 10));
  assert.ok(existsSync(runs));
  const wait = spawnSync(process.execPath, [entry, 'wait', 'sample', '--json'], { cwd: root, env, encoding: 'utf8', shell: false, timeout: 30000 });
  assert.equal(wait.status, 0, wait.stderr + wait.stdout);
  assert.equal(await exit, 0);
  const rows = readFileSync(runs, 'utf8').trim().split('\n').map(JSON.parse);
  const adjustment = rows.find(row => row.event === 'concurrency-adjust');
  const sample = readFileSync(join(home, 'resources.jsonl'), 'utf8').trim().split('\n').map(JSON.parse).find(row => row.event === 'end');
  assert.equal(sample.freeGb, 1.46);
  assert.ok(rows.findIndex(row => row.event === 'concurrency-adjust') < rows.findIndex(row => row.event === 'end'));
  assert.deepEqual(JSON.parse(wait.stdout).concurrencyAdjust, { event: adjustment.event, old: 2, new: 1, reason: adjustment.reason, at: sample.at, task: 'sample', taskId: rows.find(row => row.event === 'start').id });
  const second = spawnSync(process.execPath, [entry, 'second task', '--name', 'second', '--profile', 'fake'], { cwd: root, env, encoding: 'utf8', shell: false, timeout: 30000 });
  assert.equal(second.status, 0, second.stderr + second.stdout);
  const waitB = spawnSync(process.execPath, [entry, 'wait', 'second', '--json'], { cwd: root, env, encoding: 'utf8', shell: false, timeout: 30000 });
  assert.equal(waitB.status, 0, waitB.stderr);
  assert.equal(JSON.parse(waitB.stdout).concurrencyAdjust, null);
  const textB = spawnSync(process.execPath, [entry, 'wait', 'second'], { cwd: root, env, encoding: 'utf8', shell: false, timeout: 30000 });
  assert.doesNotMatch(textB.stdout, /\u5e76\u53d1\u4e0a\u9650 \d+\u2192/);
  const waitA = spawnSync(process.execPath, [entry, 'wait', 'sample', '--json'], { cwd: root, env, encoding: 'utf8', shell: false, timeout: 30000 });
  assert.equal(JSON.parse(waitA.stdout).concurrencyAdjust.task, 'sample');
});

test('假执行者结束后记录资源，wait 给出资源和待验收', t => {
  const base = mkdtempSync(join(tmpdir(), 'ar-summary-')), root = join(base, 'repo'), home = join(base, 'home');
  t.after(() => rmSync(base, { recursive: true, force: true }));
  mkdirSync(root); mkdirSync(home);
  const git = (...args) => { const r = spawnSync('git', args, { cwd: root, encoding: 'utf8', shell: false }); assert.equal(r.status, 0, r.stderr); };
  git('init', '-q'); git('config', 'user.name', 'Test'); git('config', 'user.email', 'test@example.invalid');
  writeFileSync(join(root, 'fixture.txt'), 'fixture'); git('add', 'fixture.txt'); git('commit', '-qm', 'fixture');
  writeFileSync(join(home, 'config.json'), JSON.stringify({ v: 2, managed: false, watchWindow: 'never', defaultProfile: 'fake', profiles: { fake: { adapter: 'fake', label: 'fake', enabled: true, events: [], report: 'ok', exit: 0 } } }));
  const env = { ...process.env, AGENT_ROUTER_HOME: home, AR_NO_WATCH: '1', AR_WORKTREE_ROOT: join(base, 'worktrees') };
  const entry = fileURLToPath(new URL('../../core/ar.mjs', import.meta.url));
  const run = args => spawnSync(process.execPath, [entry, ...args], { cwd: root, env, encoding: 'utf8', shell: false, timeout: 30000 });
  const cli = new URL('../../core/lib/cli.mjs', import.meta.url).href;
  const script = `(async () => { const { main } = await import(${JSON.stringify(cli)}); process.exitCode = await main(['示例任务', '--name', '示例', '--profile', 'fake'], { scriptPath: ${JSON.stringify(entry)} }); setTimeout(() => {}, 1500); })();`;
  const dispatched = spawnSync(process.execPath, ['-e', script], { cwd: root, env, encoding: 'utf8', shell: false, timeout: 30000 });
  assert.equal(dispatched.status, 0, dispatched.stderr + dispatched.stdout);
  const samples = readFileSync(join(home, 'resources.jsonl'), 'utf8').trim().split('\n').map(JSON.parse);
  assert.equal(samples.length, 1); assert.equal(samples[0].event, 'end');
  const file = join(home, 'runs.jsonl');
  const rows = readFileSync(file, 'utf8').trim().split('\n').map(JSON.parse);
  const start = rows.find(row => row.event === 'start');
  writeFileSync(file, rows.map(row => JSON.stringify(row === start ? { ...row, worktree: true } : row)).join('\n') + '\n');
  const event = { event: 'concurrency-adjust', old: 1, new: 2, reason: '资源充足', at: Date.now(), task: '\u793a\u4f8b' };
  writeFileSync(file, JSON.stringify({ v: 1, ...event }) + '\n', { flag: 'a' });
  const config = JSON.parse(readFileSync(join(home, 'config.json'), 'utf8'));
  config.concurrency = 'auto';
  writeFileSync(join(home, 'config.json'), JSON.stringify(config));
  writeFileSync(join(home, 'concurrency-state.json'), JSON.stringify({ limit: 2, lastAt: event.at, window: [], event }));
  const nextText = run(['next']);
  assert.match(nextText.stdout, /并发上限 1→2/);
  const nextJson = JSON.parse(run(['next', '--json']).stdout);
  assert.deepEqual(nextJson.concurrencyAdjust, event);
  const text = run(['wait', '示例']);
  assert.match(text.stdout, /并发上限 1→2/);
  assert.equal(text.status, 0, text.stderr); assert.match(text.stdout, /资源：CPU \d+%/); assert.match(text.stdout, /待验收（1）：示例/);
  const json = run(['wait', '示例', '--json']);
  assert.equal(json.status, 0, json.stderr);
  const result = JSON.parse(json.stdout); assert.deepEqual(result.concurrencyAdjust, event); assert.ok(result.resources); assert.equal(result.awaiting[0].name, '示例');
  // 别的项目里同名任务触发的调整（任务 id 不同）不算本任务的；同 id 的才算；省略记录名时按定位到的任务匹配。
  const other = { event: 'concurrency-adjust', old: 2, new: 3, reason: '资源充足', at: Date.now(), task: '示例', taskId: 'other-project-task' };
  writeFileSync(file, JSON.stringify({ v: 1, ...other }) + '\n', { flag: 'a' });
  assert.deepEqual(JSON.parse(run(['wait', '示例', '--json']).stdout).concurrencyAdjust, event);
  const own = { ...other, old: 3, new: 4, taskId: start.id };
  writeFileSync(file, JSON.stringify({ v: 1, ...own }) + '\n', { flag: 'a' });
  assert.deepEqual(JSON.parse(run(['wait', '示例', '--json']).stdout).concurrencyAdjust, own);
  assert.deepEqual(JSON.parse(run(['wait', '--json']).stdout).concurrencyAdjust, own);
  writeFileSync(join(home, 'concurrency-state.json'), '{');
  const recovered = run(['wait', '\u793a\u4f8b', '--json']);
  assert.equal(recovered.status, 0, recovered.stderr);
  assert.match(JSON.parse(recovered.stdout).warnings.join(' '), /\u635f\u574f/);
  assert.doesNotMatch(JSON.parse(run(['next', '--json']).stdout).warnings.join(' '), /\u635f\u574f/);
});

