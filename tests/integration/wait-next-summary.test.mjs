test('有门禁时结束采样复用执行者退出时的快照', t => {
  const base = mkdtempSync(join(tmpdir(), 'ar-summary-gate-')), root = join(base, 'repo'), home = join(base, 'home');
  t.after(() => rmSync(base, { recursive: true, force: true }));
  mkdirSync(root); mkdirSync(home);
  const git = (...args) => { const r = spawnSync('git', args, { cwd: root, encoding: 'utf8', shell: false }); assert.equal(r.status, 0, r.stderr); };
  git('init', '-q'); git('config', 'user.name', 'Test'); git('config', 'user.email', 'test@example.invalid');
  writeFileSync(join(root, '.gitignore'), '.agent-runs/\n');
  writeFileSync(join(root, 'task.md'), '---\nid: 900\ntitle: sample\ntype: code\nexpect_commit: false\nallowed_paths:\n  - src/**\nverify:\n  - node -e "setTimeout(() => {}, 700)"\n---\n\nSample.\n');
  git('add', '.gitignore', 'task.md'); git('commit', '-qm', 'fixture');
  writeFileSync(join(home, 'config.json'), JSON.stringify({ v: 2, managed: false, watchWindow: 'never', defaultProfile: 'fake', profiles: { fake: { adapter: 'fake', label: 'fake', enabled: true, events: [], report: 'ok', exit: 0 } } }));
  const env = { ...process.env, AGENT_ROUTER_HOME: home, AR_NO_WATCH: '1', AR_WORKTREE_ROOT: join(base, 'worktrees') };
  const entry = fileURLToPath(new URL('../../core/ar.mjs', import.meta.url));
  const dispatched = spawnSync(process.execPath, [entry, 'dispatch', 'task.md', '--name', 'gate', '--profile', 'fake'], { cwd: root, env, encoding: 'utf8', shell: false, timeout: 30000 });
  assert.equal(dispatched.status, 0, dispatched.stderr + dispatched.stdout);
  const rows = readFileSync(join(home, 'runs.jsonl'), 'utf8').trim().split('\n').map(JSON.parse);
  assert.ok(rows.some(row => row.event === 'gate' && row.ok));
  const endEvent = rows.find(row => row.event === 'end');
  const sample = JSON.parse(readFileSync(join(home, 'resources.jsonl'), 'utf8').trim());
  assert.equal(sample.event, 'end');
  t.diagnostic(`gate: ${sample.at - endEvent.at} ms`);
});
